-- vTemple sample database — FRESH schema for local MySQL development/demo.
--
-- This is NOT the legacy SQL Server schema (that one must stay untouched —
-- see /CLAUDE.md rule 1, used when DB_ENGINE is pymssql/pyodbc). This file
-- creates a brand-new, self-contained MySQL database with the same table
-- and column NAMES the backend services already use (TrnHdrSEVA, SEVAID,
-- MstSANNIDHI, ...) so the exact same service code (seva.py, hall.py,
-- ledger.py, receipt.py, masters.py) — including the two fixes (cancel
-- reversal, hall overlap) — runs unchanged against it. Real foreign keys
-- and AUTO_INCREMENT are used throughout since there is no legacy quirk to
-- preserve here.
--
-- Run:  mysql -h127.0.0.1 -P3307 -uroot -p < sql/mysql_schema.sql

CREATE DATABASE IF NOT EXISTS vtemple_sample CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE vtemple_sample;

